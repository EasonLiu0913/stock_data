'use strict';
const assert=require('node:assert/strict');
const {plan}=require('../scripts/plan_video_data_recovery');
const report={mode:'READ_ONLY_NO_DISPATCH',date:'20261008',items:[{id:'breadth_rising',status:'MISSING',recovery:'workflow_unverified'},{id:'breadth_falling',status:'MISSING',recovery:'workflow_unverified'},{id:'foreign_net',status:'PRESENT_UNVERIFIED',recovery:'dedicated_workflow_unverified'}]};
const p=plan(report);
assert.equal(p.mode,'PLAN_ONLY_NO_DISPATCH');
assert.equal(p.actions.length,2);
assert.equal(p.actions[0].decision,'BLOCKED');
assert(p.actions.every(a=>a.fields.length===1));
const candidate=plan(report,{breadth_rising:{workflow_path:'.github/workflows/verified.yml',verified_data_only:true,side_effect_audit:'PASS',input_date:'date'}});
assert.equal(candidate.actions.find(x=>x.workflow_path==='.github/workflows/verified.yml').decision,'DRY_RUN_CANDIDATE_ONLY');
const mixed=plan(report,{breadth_rising:{workflow_path:'.github/workflows/verified.yml',verified_data_only:true,side_effect_audit:'PASS',input_date:'date'},breadth_falling:{workflow_path:'.github/workflows/verified.yml',verified_data_only:false,side_effect_audit:'PASS',input_date:'date'}});
assert.equal(mixed.actions.find(x=>x.fields.some(f=>f.id==='breadth_falling')).decision,'BLOCKED');
assert.equal(mixed.actions.find(x=>x.workflow_path==='.github/workflows/verified.yml').fields.length,1);
assert.throws(()=>plan({items:[]}),/Untrusted/);
console.log('PASS read-only planner blocks unmapped recovery and does not dispatch');
